import { createHash } from 'node:crypto';
import { promises as fs } from 'node:fs';
import { dirname } from 'node:path';
import { z } from 'zod';
import {
  DEFAULT_CLIPBOARD_PREFERENCES,
  type ClipboardClip,
  type ClipboardPreferences,
} from '../shared/clipboard';

export const MAX_IMAGE_BYTES = 32 * 1024 * 1024;
// Images are stored as base64. Apply the image limit to PNG bytes, not its encoded string.
export const MAX_CLIP_BYTES = Math.ceil(MAX_IMAGE_BYTES / 3) * 4;
export const MAX_HISTORY_BYTES = 128 * 1024 * 1024;
export const MAX_HISTORY_ITEMS = 200;
const preferencesSchema = z.object({
  paused: z.boolean(),
  hoverEnabled: z.boolean(),
  retentionDays: z.union([z.literal(1), z.literal(7), z.literal(30)]),
  accelerator: z.string().max(80),
});
const clipSchema = z.object({
  id: z.string().regex(/^[a-f0-9]{64}$/),
  kind: z.enum(['text', 'image']),
  content: z.string().max(MAX_CLIP_BYTES * 2),
  preview: z.string().max(200000),
  createdAt: z.number().finite(),
  pinned: z.boolean(),
});
const savedSchema = z.object({
  version: z.literal(1),
  preferences: preferencesSchema,
  clips: z.array(clipSchema).max(MAX_HISTORY_ITEMS),
});
type Saved = z.infer<typeof savedSchema>;

export function clipId(kind: ClipboardClip['kind'], content: string) {
  return createHash('sha256').update(kind).update('\0').update(content).digest('hex');
}
export function excludedClipboardType(types: readonly string[]) {
  return types.some((type) =>
    /org\.nspasteboard\.(ConcealedType|TransientType|AutoGeneratedType)|com\.agilebits\.onepassword/i.test(
      type,
    ),
  );
}
export function clipboardContentType(types: readonly string[]) {
  const image = (
    [
      'image/png',
      'image/jpeg',
      'image/tiff',
      'image/bmp',
      'image/webp',
      'electron application/osclipboard;format="public.png"',
      'electron application/osclipboard;format="Apple PNG pasteboard type"',
      'electron application/osclipboard;format="public.tiff"',
      'electron application/osclipboard;format="NeXT TIFF v4.0 pasteboard type"',
    ] as const
  ).find((type) => types.includes(type));
  // A screenshot can include a temporary file reference alongside its pixels.
  // Skip file-only copies, but never discard an explicit image representation.
  if (image) return image;
  if (types.some((type) => /public\.file-url|NSFilenamesPboardType/i.test(type))) return;
  return types.includes('text/plain') ? 'text/plain' : undefined;
}
function trimHistory(state: Saved, now: number) {
  state.clips = state.clips
    .filter(
      (clip) => clip.pinned || now - clip.createdAt < state.preferences.retentionDays * 86400000,
    )
    .sort((a, b) => Number(b.pinned) - Number(a.pinned) || b.createdAt - a.createdAt);
  let size = 0;
  state.clips = state.clips.filter((clip, index) => {
    size += Buffer.byteLength(clip.content) + Buffer.byteLength(clip.preview);
    return index < MAX_HISTORY_ITEMS && size <= MAX_HISTORY_BYTES;
  });
}

// One private, atomically replaced file; the caller supplies the platform encryption codec.
export class ClipboardHistory {
  private state: Saved = {
    version: 1,
    preferences: { ...DEFAULT_CLIPBOARD_PREFERENCES },
    clips: [],
  };
  private queue: Promise<unknown> = Promise.resolve();
  private ready = false;
  constructor(
    private path: string,
    private codec: { encode(text: string): Buffer; decode(data: Buffer): string },
    private changed: () => void,
    private now = Date.now,
  ) {}
  async initialize() {
    let data: Buffer | undefined;
    try {
      const stat = await fs.stat(this.path);
      if (stat.size > MAX_HISTORY_BYTES * 3) throw Error('Файл истории слишком большой');
      data = await fs.readFile(this.path);
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
    }
    if (data) this.state = savedSchema.parse(JSON.parse(this.codec.decode(data)));
    this.ready = true;
    await this.prune();
  }
  getPreferences() {
    return { ...this.state.preferences };
  }
  snapshot() {
    return structuredClone(this.state);
  }
  private update(operation: (next: Saved) => void) {
    const result = this.queue.then(async () => {
      if (!this.ready) throw Error('Хранилище истории недоступно');
      const next = structuredClone(this.state);
      operation(next);
      trimHistory(next, this.now());
      if (JSON.stringify(next) === JSON.stringify(this.state)) return;
      const encoded = this.codec.encode(JSON.stringify(next));
      await fs.mkdir(dirname(this.path), { recursive: true, mode: 0o700 });
      const temporary = this.path + '.tmp';
      await fs.writeFile(temporary, encoded, { mode: 0o600 });
      await fs.rename(temporary, this.path);
      this.state = next;
      this.changed();
    });
    this.queue = result.catch(() => {});
    return result;
  }
  add(kind: ClipboardClip['kind'], content: string, preview: string) {
    if (!content || Buffer.byteLength(content) > MAX_CLIP_BYTES || preview.length > 200000)
      return Promise.resolve();
    return this.update((next) => {
      if (next.preferences.paused) return;
      const id = clipId(kind, content);
      const existing = next.clips.find((clip) => clip.id === id);
      next.clips = next.clips.filter((clip) => clip.id !== id);
      next.clips.unshift({
        id,
        kind,
        content,
        preview,
        createdAt: this.now(),
        pinned: existing?.pinned || false,
      });
    });
  }
  preferences(patch: Partial<ClipboardPreferences>) {
    return this.update((next) => {
      next.preferences = preferencesSchema.parse({ ...next.preferences, ...patch });
    });
  }
  pin(id: string, pinned: boolean) {
    return this.update((next) => {
      const clip = next.clips.find((item) => item.id === id);
      if (!clip) throw Error('Запись уже удалена');
      clip.pinned = pinned;
    });
  }
  remove(id: string) {
    return this.update((next) => {
      next.clips = next.clips.filter((clip) => clip.id !== id);
    });
  }
  clear() {
    return this.update((next) => {
      next.clips = [];
    });
  }
  prune() {
    return this.update(() => {});
  }
  flush() {
    return this.queue;
  }
}
